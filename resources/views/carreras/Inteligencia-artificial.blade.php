@section('descripcion-perfil-egreso')
    <p>El o la egresada de la carrera de Técnico en Inteligencia Artificial proporciona al estudiante la preparación para:</p>
    <ul>
        <li>Fomenta una cultura de emprendimiento al desarrollar propuestas innovadoras en su desempeño profesional, promoviendo el desarrollo humano y social.</li>
        <li>Fortalece el desarrollo de soluciones basadas en Inteligencia Artificial para abordar las necesidades del sector productivo, optimizando procesos y toma de decisiones informadas.</li>
        <li>Hace uso de datos como insumo para proceso de aprendizaje automático, lo que contribuye a la resolución de problemas de optimización y al mejoramiento de la eficiencia (Machine Learning) en contextos industriales y de servicios.</li>
        <li>Emplea modelos de optimización para resolver problemas complejos mediante herramientas computacionales, aplicado a procesos con base en redes neuronales artificiales en contextos industriales y de servicios.</li>
        <li>Desarrolla soluciones tecnológicas con generación de conocimiento considerando recursos sostenibles en contextos industriales y de servicios.</li>
        <li>Gestiona datos y los transforma en el uso de una técnica de procesamiento de datos empleando estructuras diseñadas, permitiendo su análisis y uso efectivo en entornos industriales y de servicios.</li>
        <li>Presenta datos procesados con modelos lógicos para agilizar la inteligencia de negocio, lo que permite tomar decisiones estratégicas basadas en datos en diversos contextos laborales.</li>
        <li>Utiliza modelos de aprendizaje basados en las actividades o proyectos de una empresa, proporcionando información valiosa para la toma de decisiones estratégicas.</li>
        <li>Domina técnicas de generación de conocimiento que le permite analizar y extraer información valiosa de datos en contextos industriales y de servicios.</li>
    </ul>
@endsection

