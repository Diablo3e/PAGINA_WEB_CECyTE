@section('descripcion-perfil-egreso')
      <p>La formación que ofrece la carrera de Técnico en Ciberseguridad permite al egresado, a través de la articulación de saberes de diversos campos, realizar actividades dirigidas a salvaguardar la integridad de los sistemas informáticos contra amenazas cibernéticas, empleando herramientas, procedimientos, aplicación de la normativa vigente de seguridad, para mantener los sistemas en operación en un entorno digital y conectado, alineando sus habilidades para coadyuvar con los objetivos de desarrollo sustentable.</p>
      <p>Facilita al egresado su incorporación al mundo laboral en sitios de inserción como servicios de diseño de sistemas de cómputo, infraestructura de servicios de cómputo, programación de datos, hospedaje de páginas de internet, consultoría de informática y gestión de instalaciones informáticas, instalación y reparación de redes, equipos y sistemas computacionales, para desempeñarse como técnico en la instalación y reparación de redes, equipos y sistemas computacionales, administradores de bases de datos y redes de computadora; o en el desarrollo de procesos productivos independientes, de acuerdo con sus intereses profesionales y necesidades de su entorno social.</p>
@endsection

