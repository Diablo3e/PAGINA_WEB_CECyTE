@section('descripcion-perfil-egreso')
    <p>La formación que ofrece la carrera Técnica en Semiconductores y Microelectrónica permite al egresado, a través de la articulación de saberes de diversos campos, realizar actividades dirigidas a desempeñar funciones relacionadas con la manufactura de dispositivos semiconductores, entre las que se incluyen: </p>
    <ul>
        <li>Verifica circuitos integrados para la solución de fallas en circuitos electrónicos, aplicando normas técnicas nacionales e internacionales.</li>
        <li>Realiza mediciones de dispositivos semiconductores para la caracterización de parámetros técnicos de acuerdo con la hoja de datos de los fabricantes.</li>
        <li>Auxilia en los procesos de circuitos integrados con el uso de tecnología de manufactura avanzada para asegurar la calidad de fabricación de los dispositivos semiconductores.</li>
        <li>Utiliza técnicas estadísticas para reducir la generación de desperdicios de dispositivos semiconductores en los procesos de producción.</li>
        <li>Utiliza equipos de medición para interpretación de magnitudes y parámetros técnicos de acuerdo con las normas técnicas nacionales e internacionales.</li>
        <li>Colabora en proyectos de ingeniería en semiconductores considerando el medio ambiente y un desarrollo sustentable.</li>
        <li>Participa en proyectos de mejora continua, respetando las normas de calidad establecidas por organismos internacionales que las regulan.</li>
        <li>Utiliza software asistido por computadora para auxiliar en proyectos de diseño de ingeniería con dispositivos semiconductores. </li>
        <li>Interpreta diagramas electrónicos con semiconductores para realizar mantenimientos preventivos y correctivos en áreas de producción de dispositivos semiconductores.</li>
        <li>Repara tarjetas electrónicas impresas que contienen dispositivos semiconductores.</li>
    </ul>
@endsection

