    <ul>
        <li>Resuelve problemas mediante el uso de operaciones y procesos aritméticos, geométricos y algebraicos </li>
        <li>Interactúa en diferentes contextos utilizando el lenguaje oral y escrito</li>
        <li>Maneja hábitos de estudio y técnicas de aprendizaje</li>
        <li>Aplica las tecnologías de la información y comunicación</li>
        <li>Observa reglas de convivencia para la vida en la sociedad</li>
    </ul>
@endsection

@section('descripcion-perfil-egreso')
    <p>La formación que ofrece la carrera de Técnico en mecatrónica permite al egresado, a través de la articulación de saberes de diversos campos, realizar actividades dirigidas a: Realiza circuitos eléctricos, electrónicos midiendo las variables que integran el sistema mecatrónico. Implementa los elementos mecánicos en un sistema mecatrónico Programa sistemas mecatrónicos y verifica su funcionamiento. Desarrolla procesos de manufactura. Mantiene e Integra sistemas mecatrónicos.</p>
@endsection

