@section('descripcion-perfil-egreso')
    <p>La formación que ofrece la carrera de Técnico en Electromovilidad permite al egresado, a través de la articulación de saberes de diversos campos, realizar actividades dirigidas a la Electromovilidad basados en procedimientos que integran la seguridad y la calidad al realizar procedimientos donde:</p>
    <ul>
        <li>Verifica estado y funcionamiento de sistemas mecánicos, circuitos eléctricos y electrónicos en vehículos híbridos y eléctricos.</li>
        <li>Repara fallas técnicas de sistemas mecánicos, circuitos eléctricos y electrónicos en vehículos híbridos y eléctricos.</li>
        <li>Diagnostica estado y funcionamiento de sistemas mecánicos, circuitos eléctricos y electrónicos en vehículos eléctricos.</li>
        <li>Mantiene el funcionamiento de componentes mecánicos, eléctricos y electrónicos en vehículos híbridos.</li>
        <li>Diagnostica estado y funcionamiento en vehículos eléctricos.</li>
        <li>Corrige fallas técnicas en vehículos eléctricos.</li>
    </ul>
    <p>La formación de la carrera busca preparar a los estudiantes para una participación exitosa en el ámbito de la electromovilidad y la movilidad sostenible.</p>
@endsection

