@section('descripcion-carrera')
    <p>La carrera de Técnico en Electromovilidad proporciona al estudiante la preparación profesional integral en una área emergente, nueva e innovadora en el mercado laboral de la movilidad pública, privada y de la economía nacional, ofreciéndole la posibilidad de que al egresar pueda incorporarse a un mercado ya establecido con una alta demanda de técnicos especializados en electromovilidad.</p>
    <p>La carrera de Técnico en Electromovilidad se justifica por varias razones fundamentales a continuación, se detallan las razones más importantes:</p>
    <ul>
        <li>Relevancia en el Contexto Global: La electromovilidad está experimentando un crecimiento acelerado en todo el mundo debido a su importancia en la reducción de las emisiones de gases de efecto invernadero y la mitigación del cambio climático.</li> 
        <li>Demanda del Mercado Laboral: La industria de vehículos eléctricos y la infraestructura de carga asociada están en constante expansión y crecimiento en México, esto crea una demanda creciente de profesionales capacitados en electromovilidad, desde técnicos hasta ingenieros.</li>
    </ul>

@endsection

