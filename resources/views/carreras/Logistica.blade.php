@section('descripcion-carrera')
  <p>La carrera de Técnico en Logística desarrolla en el estudiante la preparación profesional para la gestión en la adquisición de mercancías y servicios, la organización del flujo de mercancías en almacén, la gestión del tráfico de mercancías de importación y exportación y la distribución física de mercancías, así como la cotización de los costos de la cadena de suministro. Estas competencias posibilitan al egresado su incorporación al mundo laboral, continuar su trayectoria educativa o desarrollar procesos productivos independientes, de acuerdo con sus intereses profesionales o las necesidades en su entorno social.</p> 
@endsection

@section('descripcion-perfil-ingreso')
    <p>Los aspirantes a ingresar a nuestros planteles, deberán haber concluido su educación media básica y cumplir con los requisitos contemplados en la normas específicas de Servicios Escolares; además de contar con la siguientes habilidades:</p>
    <ul>
        <li>Resuelve problemas mediante el uso de operaciones y procesos aritméticos, geométricos y algebraicos</li>
        <li>Interactúa en diferentes contextos utilizando el lenguaje oral y escrito</li>
        <li>Maneja hábitos de estudio y técnicas de aprendizaje</li>
        <li>Aplica las tecnologías de la información y comunicación</li>
        <li>Observa reglas de convivencia para la vida en la sociedad potencia</li>
    </ul>
@endsection

@section('descripcion-perfil-egreso')
    <p>La formación que ofrece la carrera de Técnico en Logística permite al egresado, a través de la articulación de saberes de diversos campos, realizar actividades dirigidas a documentar la adquisición de mercancías y servicios, recibir, organizar y controlar las mercancías en almacén, gestionar la documentación y la transportación de mercancías de importación y exportación, organizar la distribución de mercancías al cliente, brindar servicio al cliente sobre el envío de mercancías, calcular los costos directos e indirectos y gestionar el presupuesto de la cadena de suministro.</p>
@endsection

